type TrackedFeatureUsageId = 'bazar_memo' | 'floating_assistant' | 'tax_report' | 'shared_access';

interface FeatureGuideState {
  dismissed: FeatureTipId[];
  used: TrackedFeatureUsageId[];
}

function getFeatureGuideStorageKey(uid?: string | null): string {
  return `orthogro_feature_guide_v1_${uid || 'guest'}`;
}

function readFeatureGuideState(storageKey: string): FeatureGuideState {
  try {
    const raw = localStorage.getItem(storageKey);
    if (!raw) return { dismissed: [], used: [] };
    const parsed = JSON.parse(raw) as Partial<FeatureGuideState>;
    const dismissed = Array.isArray(parsed.dismissed)
      ? parsed.dismissed.filter((id): id is FeatureTipId =>
          ALL_FEATURE_TIP_IDS.includes(id as FeatureTipId)
        )
      : [];
    const used = Array.isArray(parsed.used)
      ? parsed.used.filter(
          (id): id is TrackedFeatureUsageId =>
            id === 'bazar_memo' ||
            id === 'floating_assistant' ||
            id === 'tax_report' ||
            id === 'shared_access'
        )
      : [];
    return { dismissed, used };
  } catch {
    return { dismissed: [], used: [] };
  }
}

function writeFeatureGuideState(storageKey: string, state: FeatureGuideState) {
  try {
    localStorage.setItem(storageKey, JSON.stringify(state));
  } catch {
    // ignore storage errors
  }
}

