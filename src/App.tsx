  // Transaction CRUD
  const saveTransactionDrafts = async (
    draftList: TransactionDraft[],
    navigateHome: boolean
  ): Promise<boolean> => {
    if (isReadOnlyPartner) {
      notify('info', t.sharing.readOnlyToast);
      return false;
    }

    for (let i = 0; i < draftList.length; i++) {
      const amt = parseFloat(draftList[i].amount);
      if (!Number.isFinite(amt) || amt <= 0) {
        notify('error', `${t.toasts.invalidAmountPrefix}${i + 1}`);
        return false;
      }
      if (
        draftList[i].type === 'transfer' &&
        draftList[i].fromWallet === draftList[i].toWallet
      ) {
        notify('error', `${t.txForm.entryLabel} #${i + 1}: ${t.toasts.sameAccountTransfer}`);
        return false;
      }
    }

    const buildTxPayload = (entry: TransactionDraft, id: string): Transaction => {
      const trimmedNote = entry.note.trim();
      const defaultTitle =
        entry.type === 'transfer'
          ? t.common.transfer
          : entry.type === 'lend'
          ? trimmedNote
            ? trimmedNote.slice(0, 200)
            : t.common.lend
          : entry.type === 'borrow'
          ? trimmedNote
            ? trimmedNote.slice(0, 200)
            : t.common.borrow
          : entry.type === 'income'
          ? entry.category || t.common.income
          : entry.subCategory.trim() || entry.category || t.common.expense;
      const amt = parseFloat(entry.amount);
      const rawDate = entry.date || getTodayISO();

      const tx: Transaction = {
        id,
        title: (entry.title.trim() || defaultTitle).slice(0, 200),
        amount: amt,
        type: entry.type,
        date: formatDisplayDate(rawDate, currentLanguage),
        rawDate,
        resolved: false,
      };

      if (entry.type === 'transfer') {
        tx.fromWallet = entry.fromWallet;
        tx.toWallet = entry.toWallet;
        tx.category = 'General';
        if (entry.useCharge && entry.charge) {
          tx.charge = Math.max(0, parseFloat(entry.charge) || 0);
        }
      } else if (entry.type === 'lend' || entry.type === 'borrow') {
        tx.wallet = entry.wallet;
        tx.category = 'General';
        tx.remainingBalance = amt;
      } else {
        tx.wallet = entry.wallet;
        tx.category = entry.category;
        if (entry.type === 'expense' && entry.subCategory.trim()) {
          tx.subCategory = entry.subCategory.trim().slice(0, 100);
        }
      }

      const shouldStoreNote =
        trimmedNote &&
        !(
          (entry.type === 'lend' || entry.type === 'borrow') &&
          !entry.title.trim() &&
          trimmedNote.length <= 200
        );
      if (shouldStoreNote) {
        tx.note = trimmedNote.slice(0, 2000);
      }
      return tx;
    };

    const prepared = draftList.map((entry) => {
      const isEdit = Boolean(entry.id);
      const id = entry.id || generateSafeId('tx');
      return {
        isEdit,
        tx: buildTxPayload(entry, id),
      };
    });

    const editedIds = new Set(prepared.filter((p) => p.isEdit).map((p) => p.tx.id));
    const nextTransactions = [
      ...prepared.map((p) => p.tx),
      ...transactions.filter((t) => !editedIds.has(t.id)),
    ].sort((a, b) => b.rawDate.localeCompare(a.rawDate));

    if (currentUser && activeOwnerId) {
      const uid = activeOwnerId;
      const batch = writeBatch(db);

      prepared.forEach(({ isEdit, tx }) => {
        const ref = doc(db, 'users', uid, 'transactions', tx.id);

        if (isEdit) {
          const updateData: Record<string, unknown> = {
            title: tx.title,
            amount: tx.amount,
            type: tx.type,
            date: tx.date,
            rawDate: tx.rawDate,
            resolved: transactions.find((t) => t.id === tx.id)?.resolved ?? false,
            updatedAt: serverTimestamp(),
            category: tx.category !== undefined ? tx.category : deleteField(),
            subCategory: tx.subCategory !== undefined ? tx.subCategory : deleteField(),
            wallet: tx.wallet !== undefined ? tx.wallet : deleteField(),
            fromWallet: tx.fromWallet !== undefined ? tx.fromWallet : deleteField(),
            toWallet: tx.toWallet !== undefined ? tx.toWallet : deleteField(),
            charge: tx.charge !== undefined ? tx.charge : deleteField(),
            remainingBalance:
              tx.remainingBalance !== undefined ? tx.remainingBalance : deleteField(),
            note: tx.note !== undefined ? tx.note : deleteField(),
          };
          batch.update(ref, updateData);
        } else {
          const createData: Record<string, unknown> = {
            ownerId: uid,
            title: tx.title,
            amount: tx.amount,
            type: tx.type,
            date: tx.date,
            rawDate: tx.rawDate,
            resolved: false,
            createdAt: serverTimestamp(),
            updatedAt: serverTimestamp(),
          };
          if (tx.category !== undefined) createData.category = tx.category;
          if (tx.subCategory !== undefined) createData.subCategory = tx.subCategory;
          if (tx.wallet !== undefined) createData.wallet = tx.wallet;
          if (tx.fromWallet !== undefined) createData.fromWallet = tx.fromWallet;
          if (tx.toWallet !== undefined) createData.toWallet = tx.toWallet;
          if (tx.charge !== undefined) createData.charge = tx.charge;
          if (tx.remainingBalance !== undefined) {
            createData.remainingBalance = tx.remainingBalance;
          }
          if (tx.note !== undefined) createData.note = tx.note;
          batch.set(ref, createData);
        }
      });

      try {
        await batch.commit();
      } catch (err) {
        handleFirestoreError(err, OperationType.WRITE, `users/${uid}/transactions`);
      }
    } else {
      setTransactions(nextTransactions);
    }

    const linkedRecurringId = !draftList[0]?.id ? pendingRecurringBillId : null;
    if (linkedRecurringId) {
      const paidDate = draftList[0]?.date || getTodayISO();
      const paidMonth = paidDate.slice(0, 7);
      if (currentUser && activeOwnerId) {
        if (recurringBills.some((rb) => rb.id === linkedRecurringId)) {
          const uid = activeOwnerId;
          try {
            await updateDoc(doc(db, 'users', uid, 'recurringBills', linkedRecurringId), {
              lastPaidMonth: paidMonth,
              lastPaidDate: paidDate,
              updatedAt: serverTimestamp(),
            });
          } catch (err) {
            handleFirestoreError(
              err,
              OperationType.UPDATE,
              `users/${uid}/recurringBills/${linkedRecurringId}`
            );
          }
        }
      } else {
        setRecurringBills((prev) =>
          prev.map((rb) =>
            rb.id === linkedRecurringId
              ? { ...rb, lastPaidMonth: paidMonth, lastPaidDate: paidDate }
              : rb
          )
        );
      }
      setPendingRecurringBillId(null);
    }

    const savingsSet = new Set(workspace.savingsList);
    const hasSavingsDeposit = prepared.some(
      ({ tx }) =>
        (tx.type === 'transfer' && Boolean(tx.toWallet) && savingsSet.has(tx.toWallet as string)) ||
        (tx.type === 'income' && Boolean(tx.wallet) && savingsSet.has(tx.wallet as string))
    );

    let triggeredMilestone: SavingsMilestoneEvent | null = null;
    if (hasSavingsDeposit && !activeSharedWorkspace) {
      const prevTotalSavings = computeTotalSavingsBalance(transactions, workspace.savingsList);
      const nextTotalSavings = computeTotalSavingsBalance(nextTransactions, workspace.savingsList);
      const celebrated = readCelebratedMilestones(milestoneStorageKey);
      const celebratedSet = new Set(celebrated);

      const newlyCrossedThresholds = SAVINGS_AMOUNT_MILESTONES.filter(
        (m) => prevTotalSavings < m && nextTotalSavings >= m
      );
      const uncelebratedThresholds = newlyCrossedThresholds.filter(
        (m) => !celebratedSet.has(`amount:${m}`)
      );

      if (uncelebratedThresholds.length > 0) {
        const highest = uncelebratedThresholds[uncelebratedThresholds.length - 1];
        uncelebratedThresholds.forEach((m) => celebratedSet.add(`amount:${m}`));
        writeCelebratedMilestones(milestoneStorageKey, Array.from(celebratedSet));
        triggeredMilestone = {
          id: `amount:${highest}`,
          kind: 'amount',
          threshold: highest,
        };
      } else if (savingGoals.length > 0) {
        const reachedGoal = savingGoals.find((goal) => {
          const key = `goal:${goal.id}`;
          if (celebratedSet.has(key)) return false;
          const prevPct = computeSavingGoalProgress(
            goal,
            transactions,
            workspace.savingsList,
            currentLanguage
          ).pct;
          const nextPct = computeSavingGoalProgress(
            goal,
            nextTransactions,
            workspace.savingsList,
            currentLanguage
          ).pct;
          return prevPct < 100 && nextPct >= 100;
        });

        if (reachedGoal) {
          const key = `goal:${reachedGoal.id}`;
          celebratedSet.add(key);
          writeCelebratedMilestones(milestoneStorageKey, Array.from(celebratedSet));
          triggeredMilestone = {
            id: key,
            kind: 'goal',
            goalTitle: reachedGoal.title,
          };
        }
      }
    }

    if (triggeredMilestone) {
      setActiveMilestone(triggeredMilestone);
      notify('success', t.milestone.savedDepositToast);
    } else if (hasSavingsDeposit && !draftList[0]?.id) {
      notify('success', t.milestone.savedDepositToast);
    } else {
      notify('success', draftList[0]?.id ? t.toasts.txUpdated : t.toasts.txSaved);
    }

    if (navigateHome) {
      setShowTxFormDrawer(false);
      setEntries([defaultEntry]);
      if (activeTab === 'transactions') {
        setActiveTab('home');
      }
    }
    return true;
  };

