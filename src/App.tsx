function computeTotalSavingsBalance(txList: Transaction[], savingsList: string[]): number {
  if (savingsList.length === 0) return 0;
  const savingsSet = new Set(savingsList);
  let total = 0;

  txList.forEach((tx) => {
    if (tx.type === 'income' && tx.wallet && savingsSet.has(tx.wallet)) {
      total += tx.amount;
    } else if (tx.type === 'expense' && tx.wallet && savingsSet.has(tx.wallet)) {
      total -= tx.amount;
    } else if (tx.type === 'transfer' && tx.fromWallet && tx.toWallet) {
      if (savingsSet.has(tx.fromWallet)) {
        total -= tx.amount + (tx.charge || 0);
      }
      if (savingsSet.has(tx.toWallet)) {
        total += tx.amount;
      }
    } else if (tx.type === 'lend' && tx.wallet && savingsSet.has(tx.wallet)) {
      total -= tx.amount;
    } else if (tx.type === 'borrow' && tx.wallet && savingsSet.has(tx.wallet)) {
      total += tx.amount;
    } else if (tx.type === 'partial_payment' && tx.wallet && savingsSet.has(tx.wallet)) {
      total += tx.isLendPay ? tx.amount : -tx.amount;
    } else if (
      (tx.type === 'correction' || tx.type === 'adjustment') &&
      tx.wallet &&
      savingsSet.has(tx.wallet)
    ) {
      total += tx.amount;
    }
  });

  return total;
}

function readGuestJSON<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    if (!raw) return fallback;
    return JSON.parse(raw) as T;
  } catch {
    return fallback;
  }
}

class AppErrorBoundary extends React.Component<
  { children: React.ReactNode },
  { hasError: boolean; message: string }
> {
  constructor(props: { children: React.ReactNode }) {
    super(props);
    this.state = { hasError: false, message: '' };
  }

  static getDerivedStateFromError(error: Error) {
    return { hasError: true, message: error.message || 'Unexpected application error' };
  }

  render() {
    if (this.state.hasError) {
      const errT = getTranslations(readStoredLanguage());
      return (
        <div className="flex min-h-screen items-center justify-center bg-[#F6F8F7] p-6 dark:bg-slate-950">
          <div className="w-full max-w-md rounded-2xl border border-rose-200 bg-white p-6 text-center shadow-sm dark:border-rose-900 dark:bg-slate-900">
            <h2 className="text-lg font-bold text-rose-600 dark:text-rose-400">
              {errT.app.somethingWrong}
            </h2>
            <p className="mt-2 text-xs text-slate-600 dark:text-slate-300">
              {this.state.message}
            </p>
            <button
              type="button"
              onClick={() => window.location.reload()}
              className="mt-5 rounded-xl bg-[#16845B] px-5 py-2.5 text-xs font-bold text-white hover:bg-[#126B4A]"
            >
              {errT.app.reloadApp}
            </button>
          </div>
        </div>
      );
    }
    return this.props.children;
  }
}

