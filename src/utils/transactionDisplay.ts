import type { Transaction } from '../types';

export interface TransactionDisplayLabels {
  expense: string;
  income: string;
  transfer: string;
  lend: string;
  borrow: string;
  general: string;
}

const DEFAULT_FALLBACK_TITLES = new Set([
  'expense',
  'income',
  'transfer',
  'lend',
  'borrow',
  'general',
  'খরচ',
  'ব্যয়',
  'আয়',
  'ট্রান্সফার',
  'ধার দেওয়া',
  'ধার দেওয়া',
  'ধার নেওয়া',
  'ধার নেওয়া',
  'সাধারণ',
]);

export function isAutoGeneratedTitle(
  tx: Pick<Transaction, 'title' | 'category' | 'subCategory'>,
  labels?: Partial<TransactionDisplayLabels>
): boolean {
  const title = (tx.title || '').trim();
  if (!title) return true;

  const lower = title.toLowerCase();
  if (DEFAULT_FALLBACK_TITLES.has(lower)) return true;

  if (labels) {
    const labelVals = [
      labels.expense,
      labels.income,
      labels.transfer,
      labels.lend,
      labels.borrow,
      labels.general,
    ];
    if (labelVals.some((v) => v && v.trim().toLowerCase() === lower)) {
      return true;
    }
  }

  const cat = (tx.category || '').trim().toLowerCase();
  const sub = (tx.subCategory || '').trim().toLowerCase();
  if (cat && lower === cat) return true;
  if (sub && lower === sub) return true;

  return false;
}

export type TitleSource = 'custom' | 'subCategory' | 'category';

export interface TransactionHierarchy {
  mainTitle: string;
  titleSource: TitleSource;
  extraNote: string;
  categoryLabel: string;
  subCategoryLabel: string;
}

export function getTransactionHierarchy(
  tx: Transaction,
  labels: TransactionDisplayLabels
): TransactionHierarchy {
  const trimmedNote = (tx.note || '').trim();
  const trimmedTitle = (tx.title || '').trim();
  const subCategoryLabel = (tx.subCategory || '').trim();
  const categoryLabel = (tx.category || '').trim() || labels.general;

  const hasCustomTitle = !isAutoGeneratedTitle(tx, labels);

  if (hasCustomTitle) {
    return {
      mainTitle: trimmedTitle,
      titleSource: 'custom',
      extraNote:
        trimmedNote && trimmedNote.toLowerCase() !== trimmedTitle.toLowerCase()
          ? trimmedNote
          : '',
      categoryLabel,
      subCategoryLabel,
    };
  }

  if (trimmedNote) {
    return {
      mainTitle: trimmedNote,
      titleSource: 'custom',
      extraNote: '',
      categoryLabel,
      subCategoryLabel,
    };
  }

  if (tx.type === 'transfer') {
    return {
      mainTitle: labels.transfer,
      titleSource: 'category',
      extraNote: '',
      categoryLabel,
      subCategoryLabel: '',
    };
  }

  if (tx.type === 'lend') {
    return {
      mainTitle: labels.lend,
      titleSource: 'category',
      extraNote: '',
      categoryLabel,
      subCategoryLabel: '',
    };
  }

  if (tx.type === 'borrow') {
    return {
      mainTitle: labels.borrow,
      titleSource: 'category',
      extraNote: '',
      categoryLabel,
      subCategoryLabel: '',
    };
  }

  if (subCategoryLabel) {
    return {
      mainTitle: subCategoryLabel,
      titleSource: 'subCategory',
      extraNote: '',
      categoryLabel,
      subCategoryLabel,
    };
  }

  return {
    mainTitle: categoryLabel,
    titleSource: 'category',
    extraNote: '',
    categoryLabel,
    subCategoryLabel: '',
  };
}
